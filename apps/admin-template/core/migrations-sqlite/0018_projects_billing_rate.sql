--
-- 工数を請求する明細は「時間単価 × 時間」で行金額が決まる（決定 B-2）が、
-- その単価の出どころがドメイン設計に無かった。`cost_rates` は**内部原価**の
-- レートで、採算計算にしか使わない（CLAUDE.md 1.2）— 請求単価に流用すると
-- 原価と売上が同じ数字になり、粗利が常にゼロになる。
--
-- 案件ごとに1つ持つ（NULL = 未設定）。確定済みの InvoiceLine は行金額を
-- 焼き付けるので、後からこの単価を変えても発行済みの請求書は動かない。
ALTER TABLE projects ADD COLUMN billing_hourly_rate INTEGER;
